_CHATGPT_API_FETCH_JS = r"""
async (shareId) => {
    try {
        const resp = await fetch(
            `https://chatgpt.com/backend-api/share/${shareId}`,
            { credentials: 'include',
              headers: { 'Accept': 'application/json' } }
        );
        if (!resp.ok) return { error: `HTTP ${resp.status}` };
        const data = await resp.json();

        const mapping = data && data.mapping;
        if (!mapping || typeof mapping !== 'object') {
            if (data && Array.isArray(data.linear_conversation)) {
                return { messages: data.linear_conversation
                    .map(v => v && v.message)
                    .filter(Boolean)
                    .map(m => {
                        const content = m.content || {};
                        let text = '';
                        if (Array.isArray(content.parts)) {
                            text = content.parts
                                .filter(p => typeof p === 'string')
                                .join('\n');
                        } else if (typeof content.text === 'string') {
                            text = content.text;
                        }
                        const role = (m.author && m.author.role) || 'assistant';
                        return { role: role === 'tool' ? 'assistant' : role,
                                 text: text };
                    })
                    .filter(m => m.text && m.text.trim()),
                    stats: { source: 'linear_conversation' }
                };
            }
            return { error: 'No mapping in response',
                     top_keys: data && Object.keys(data) };
        }

        const stats = {
            total_nodes: Object.keys(mapping).length,
            roles: {},
            content_types: {},
            no_message: 0,
            no_id: 0,
            system: 0,
            hidden: 0,
            empty_text: 0,
            kept: 0,
        };

        const nodes = [];
        for (const id of Object.keys(mapping)) {
            const node = mapping[id];
            if (node && node.message) nodes.push(node);
            else stats.no_message++;
        }

        nodes.sort((a, b) => {
            const ta = (a.message && a.message.create_time) || 0;
            const tb = (b.message && b.message.create_time) || 0;
            return ta - tb;
        });

        const seen = new Set();
        const messages = [];
        for (const node of nodes) {
            const m = node.message;
            if (!m) continue;
            if (!m.id) { stats.no_id++; continue; }
            if (seen.has(m.id)) continue;
            seen.add(m.id);

            const author = m.author || {};
            let role = author.role || 'unknown';
            stats.roles[role] = (stats.roles[role] || 0) + 1;

            const contentType = (m.content && m.content.content_type) || 'unknown';
            stats.content_types[contentType] = 
                (stats.content_types[contentType] || 0) + 1;

            if (role === 'system') { stats.system++; continue; }

            if (m.metadata && m.metadata.is_visually_hidden_from_conversation) {
                stats.hidden++;
            }

            const content = m.content || {};
            let text = '';
            if (Array.isArray(content.parts)) {
                text = content.parts
                    .filter(p => typeof p === 'string')
                    .join('\n');
            } else if (typeof content.text === 'string') {
                text = content.text;
            }

            if (!text || !text.trim()) { stats.empty_text++; continue; }

            stats.kept++;
            messages.push({
                role: role === 'tool' ? 'assistant' : role,
                text: text,
            });
        }

        return { messages: messages, stats: stats };
    } catch (e) {
        return { error: String(e) };
    }
}
"""


def _chatgpt_share_id(url: str):
    m = re.search(r"chatgpt\.com/share/([a-zA-Z0-9\-]+)", url)
    if not m:
        m = re.search(r"chat\.openai\.com/share/([a-zA-Z0-9\-]+)", url)
    return m.group(1) if m else None


def _wait_for_url_stable(page, sid: str, max_wait_s: float = 8.0) -> bool:
    start = time.time()
    last_url = None
    stable_since = time.time()
    while time.time() - start < max_wait_s:
        try:
            cur = page.url
        except Exception:
            return False
        if cur != last_url:
            last_url = cur
            stable_since = time.time()
        elif time.time() - stable_since > 1.5:
            return True
        _safe_wait(page, 300)
    return True


def _chatgpt_extract_via_api(page, url: str, sid: str, max_retries: int = 5):
    share_id = _chatgpt_share_id(url)
    if not share_id:
        return None, ""

    print(f"[{sid}] ChatGPT backend API share/{share_id}…")

    result = None
    for attempt in range(1, max_retries + 1):
        try:
            result = page.evaluate(_CHATGPT_API_FETCH_JS, share_id)
            break
        except Exception as e:
            msg = str(e)
            if ("Execution context was destroyed" in msg
                    or "context was destroyed" in msg.lower()
                    or "has been closed" in msg):
                print(f"[{sid}] API context destroyed "
                      f"(attempt {attempt}/{max_retries}); waiting…")
                _safe_wait(page, 2000)
                continue
            print(f"[{sid}] API call failed: {e}")
            return None, ""

    if result is None:
        print(f"[{sid}] API exhausted retries.")
        return None, ""

    if "error" in result:
        print(f"[{sid}] API error: {result.get('error')}")
        if result.get("top_keys"):
            print(f"[{sid}] API top keys: {result['top_keys']}")
        return None, ""

    stats = result.get("stats") or {}
    if stats:
        print(f"[{sid}] API raw stats:")
        print(f"[{sid}]   total_nodes     = {stats.get('total_nodes')}")
        print(f"[{sid}]   roles           = {stats.get('roles')}")
        print(f"[{sid}]   content_types   = {stats.get('content_types')}")
        print(f"[{sid}]   no_message      = {stats.get('no_message')}")
        print(f"[{sid}]   system          = {stats.get('system')}")
        print(f"[{sid}]   hidden          = {stats.get('hidden')}")
        print(f"[{sid}]   empty_text      = {stats.get('empty_text')}")
        print(f"[{sid}]   kept            = {stats.get('kept')}")

    messages = result.get("messages") or []
    if not messages:
        print(f"[{sid}] API returned 0 messages.")
        return None, ""

    parts = []
    first_user_text = ""
    first_any_text = ""
    for msg in messages:
        role = msg.get("role", "assistant")
        text = msg.get("text", "")
        candidate = text.strip().split("\n")[0][:100]
        if candidate:
            if not first_any_text and not _is_meta_message(candidate):
                first_any_text = candidate
            if (not first_user_text and role == "user"
                    and not _looks_like_code(candidate)
                    and not _is_meta_message(candidate)):
                first_user_text = candidate

        cleaned = _clean_chatgpt_markup(text)
        paragraphs = "".join(
            f"<p>{p}</p>" for p in cleaned.split("\n\n") if p.strip()
        ) or f"<p>{cleaned}</p>"
        parts.append(
            f'<section class="msg msg-{role}">{paragraphs}</section>'
        )

    if not first_user_text:
        first_user_text = first_any_text

    print(f"[{sid}] ✅ ChatGPT API: {len(messages)} messages")
    return "\n".join(parts), first_user_text



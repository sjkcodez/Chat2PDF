def _page_has(page, markers) -> bool:
    try:
        content = page.content().lower()
    except Exception:
        return False
    return any(m in content for m in markers)


def _page_has_captcha(page) -> bool:
    if _page_has(page, CAPTCHA_MARKERS):
        return True
    try:
        for frame in page.frames:
            u = (frame.url or "").lower()
            if any(k in u for k in ("recaptcha", "hcaptcha",
                                     "challenges.cloudflare")):
                return True
    except Exception:
        pass
    return False


def _page_is_consent_screen(page) -> bool:
    try:
        url = (page.url or "").lower()
        if "consent.google.com" in url:
            return True
    except Exception:
        pass
    return _page_has(page, CONSENT_MARKERS)


def _safe_wait(page, ms: int) -> bool:
    try:
        if page.is_closed():
            return False
        page.wait_for_timeout(ms)
        return True
    except Exception:
        return False


def _safe_content(page) -> str:
    try:
        if page.is_closed():
            return ""
        return page.content()
    except Exception:
        return ""



def _navigate_claude_with_retry(page, context, url: str, sid: str) -> bool:
    strategies = [
        ("commit", 30_000),
        ("domcontentloaded", 45_000),
        ("load", 60_000),
    ]
    for idx, (wait_until, timeout) in enumerate(strategies, start=1):
        try:
            print(f"[{sid}] Claude nav attempt {idx} "
                  f"(wait_until={wait_until})…")
            if idx == 2:
                try:
                    page.goto("about:blank",
                              wait_until="commit", timeout=5000)
                    _safe_wait(page, 1000)
                except Exception:
                    pass
            page.goto(url, wait_until=wait_until, timeout=timeout)
            print(f"[{sid}] ✅ Claude nav OK (strategy {idx})")
            return True
        except Exception as e:
            err = str(e)[:200]
            print(f"[{sid}] Claude nav attempt {idx} failed: {err}")
            if "ERR_INVALID_ARGUMENT" in str(e):
                raise _RetryableNavigationError(str(e))
            if idx < len(strategies):
                _safe_wait(page, 3000)
    return False


def _claude_has_login_wall(page) -> bool:
    try:
        content = page.content().lower()
    except Exception:
        return False
    login_markers = (
        "sign in to claude", "log in to claude",
        "continue with google", "continue with email",
        "this conversation is private", "conversation not found",
    )
    if not any(m in content for m in login_markers):
        return False
    try:
        if page.query_selector('[data-testid="user-message"]'):
            return False
    except Exception:
        pass
    return True


_CLAUDE_WAIT_JS = r"""
async () => {
    const sleep = (ms) => new Promise(r => setTimeout(r, ms));
    function count() {
        return document.querySelectorAll('[data-testid="user-message"]').length
             + document.querySelectorAll('.font-claude-response').length;
    }
    let last = count(); let stable = 0;
    for (let i = 0; i < 30; i++) {
        window.scrollTo(0, 0);
        document.querySelectorAll('*').forEach(el => {
            try {
                const cs = getComputedStyle(el);
                if ((cs.overflowY === 'auto' || cs.overflowY === 'scroll')
                    && el.scrollHeight > el.clientHeight + 20) {
                    el.scrollTop = 0;
                }
            } catch (e) {}
        });
        document.querySelectorAll('button, a, [role="button"]').forEach(el => {
            const t = (el.innerText || '').toLowerCase();
            if (t.includes('load earlier') || t.includes('load more')
                || t.includes('show earlier') || t.includes('earlier messages')) {
                try { el.click(); } catch (e) {}
            }
        });
        await sleep(600);
        const c = count();
        if (c > last) { last = c; stable = 0; } else { stable++; }
        if (stable >= 5) break;
    }
    return count();
}
"""


def _wait_for_claude(page, sid: str, timeout: int = 120) -> bool:
    deadline = time.time() + timeout
    last_log = 0
    print(f"[{sid}] Waiting for Claude conversation (timeout={timeout}s)…")
    while time.time() < deadline:
        try:
            if page.is_closed():
                return False
        except Exception:
            return False
        try:
            u = page.query_selector_all('[data-testid="user-message"]')
            a = page.query_selector_all('.font-claude-response')
            if u or a:
                print(f"[{sid}] ✅ Initial Claude messages: "
                      f"{len(u)} user + {len(a)} assistant")
                break
        except Exception:
            pass
        now = int(time.time())
        if now - last_log >= 20:
            print(f"[{sid}] ⏳ Still waiting for Claude… "
                  f"({int(deadline - now)}s left)")
            last_log = now
        if not _safe_wait(page, 2000):
            return False
    else:
        print(f"[{sid}] ⏰ Timeout waiting for Claude messages.")
        return False
    print(f"[{sid}] Scrolling up to load earlier messages…")
    try:
        total = page.evaluate(_CLAUDE_WAIT_JS)
        print(f"[{sid}] After scroll-up: {total} message elements")
    except Exception as e:
        print(f"[{sid}] Scroll-up JS failed: {e}")
    return True


def _accept_google_consent(page, sid: str) -> bool:
    if not _page_is_consent_screen(page):
        return True
    print(f"[{sid}] Google consent screen detected — accepting…")
    accept_selectors = [
        'button[aria-label*="Accept all"]', 'button[aria-label*="Accept"]',
        'button:has-text("Accept all")', 'button:has-text("I agree")',
        'form[action*="consent"] button',
        'div[role="button"]:has-text("Accept")',
        'button:has-text("Aceitar")', 'button:has-text("Accepter")',
        'button:has-text("Aceptar")',
    ]
    for sel in accept_selectors:
        try:
            el = page.query_selector(sel)
            if el:
                el.click(timeout=5000)
                print(f"[{sid}] Clicked consent button: {sel}")
                _safe_wait(page, 3000)
                return True
        except Exception:
            continue
    try:
        clicked = page.evaluate("""
            () => {
                const btns = Array.from(document.querySelectorAll(
                    'button, [role="button"]'));
                for (const b of btns) {
                    const txt = (b.innerText || '').toLowerCase();
                    if (txt.includes('accept') || txt.includes('agree')
                        || txt.includes('aceitar') || txt.includes('accepter')
                        || txt.includes('aceptar')) {
                        b.click(); return true;
                    }
                }
                return false;
            }
        """)
        if clicked:
            print(f"[{sid}] Clicked consent via JS fallback.")
            _safe_wait(page, 3000)
            return True
    except Exception as e:
        print(f"[{sid}] JS consent-click failed: {e}")
    print(f"[{sid}] ⚠️  No consent button — proceeding anyway.")
    return False



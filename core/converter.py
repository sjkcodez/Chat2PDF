_INVISIBLE_RE = re.compile(
    r"[\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]"
)

_CODE_PREFIX_RE = re.compile(
    r"^\s*(?:"
    r"import\s+\w|from\s+\w+\s+import|def\s+\w|class\s+\w|"
    r"#\s|//\s|/\*|\*/|"
    r"public\s+|private\s+|protected\s+|static\s+|void\s+|"
    r"const\s+\w|let\s+\w|var\s+\w|function\s+\w|"
    r"package\s+\w|using\s+\w|namespace\s+\w|"
    r"#include\s*<|<\?php|"
    r"SELECT\s+|INSERT\s+|UPDATE\s+|DELETE\s+FROM|"
    r"```\w*|~~~\w*"
    r")",
    re.IGNORECASE,
)

_CODE_LINE_RE = re.compile(r"[{};]|=>|\breturn\s|\bprint\s*\(")


def _looks_like_code(s: str) -> bool:
    if not s:
        return False
    first_line = s.strip().split("\n")[0]
    if _CODE_PREFIX_RE.match(first_line):
        return True
    if _CODE_LINE_RE.search(first_line) and len(first_line) < 80:
        return True
    return False


def _clean_invisible(s: str) -> str:
    if not s:
        return ""
    return _INVISIBLE_RE.sub("", s).strip()



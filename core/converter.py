def _wait_for_platform_conversation(page, platform: str, sid: str,
                                    timeout: int = 120):
    selectors = _PLATFORM_WAIT_SELECTORS.get(
        platform, _PLATFORM_WAIT_SELECTORS["generic"]
    )
    deadline = time.time() + timeout
    last_count = 0
    last_log = 0
    print(f"[{sid}] Waiting for {platform} conversation "
          f"(timeout={timeout}s)…")
    while time.time() < deadline:
        try:
            if page.is_closed():
                return False, "page_closed"
        except Exception:
            return False, "page_closed"
        for sel in selectors:
            try:
                els = page.query_selector_all(sel)
                if not els:
                    continue
                total = ""
                for e in els[:40]:
                    try:
                        total += (e.inner_text() or "")
                    except Exception:
                        pass
                text_len = len(total.strip())
                if text_len > 100:
                    print(f"[{sid}] ✅ {sel} → {len(els)} elements, "
                          f"{text_len} chars")
                    return True, "ready"
                if len(els) > last_count:
                    last_count = len(els)
            except Exception:
                continue
        now = int(time.time())
        if now - last_log >= 20:
            print(f"[{sid}] ⏳ Still waiting for {platform} content… "
                  f"({int(deadline - now)}s left)")
            last_log = now
        if not _safe_wait(page, 1500):
            return False, "page_closed"
    print(f"[{sid}] ⏰ Timeout waiting for {platform} conversation.")
    return False, "timeout"



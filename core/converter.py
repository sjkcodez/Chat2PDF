def _extract_chat_title(page, sid: str, fallback_text: str = None) -> str:
    title = ""
    js_first_user = ""
    try:
        raw = page.evaluate(_CHAT_TITLE_JS)
        if isinstance(raw, dict):
            title = _clean_invisible(raw.get("title") or "")
            js_first_user = _clean_invisible(raw.get("first_user") or "")
    except Exception as e:
        print(f"[{sid}] Title JS failed: {e}")

    original_lower = title.lower().strip()

    changed = True
    while changed:
        changed = False
        for noise in _TITLE_NOISE:
            if title.endswith(noise):
                title = title[:-len(noise)].strip()
                changed = True
            elif title.startswith(noise):
                title = title[len(noise):].strip()
                changed = True

    stripped_lower = title.lower().strip()
    needs_fallback = (
        not title
        or len(title) < 3
        or original_lower in _PLATFORM_DEFAULT_TITLES
        or stripped_lower in _PLATFORM_DEFAULT_TITLES
    )

    if needs_fallback:
        candidate = ""
        source = ""

        if fallback_text:
            fb = fallback_text.strip()
            if (len(fb) >= 3
                    and not _looks_like_code(fb)
                    and not _is_meta_message(fb)):
                candidate = fb
                source = "first extracted message (Python)"
            elif _is_meta_message(fb):
                print(f"[{sid}] Ignored meta-message fallback: "
                      f"{fb[:60]!r}")

        if not candidate and js_first_user and len(js_first_user) >= 3:
            if _looks_like_code(js_first_user):
                print(f"[{sid}] Ignored JS first_user "
                      f"(looks like code): {js_first_user[:40]!r}")
            elif _is_meta_message(js_first_user):
                print(f"[{sid}] Ignored JS first_user "
                      f"(meta-message): {js_first_user[:60]!r}")
            else:
                candidate = js_first_user
                source = "first user message (JS)"

        if candidate:
            first_line = candidate.split("\n")[0].strip()
            title = first_line[:100]
            print(f"[{sid}] Using {source} as title fallback")
        else:
            print(f"[{sid}] Fallback found no usable title candidate "
                  f"(fallback_text={bool(fallback_text)}, "
                  f"js_first_user={bool(js_first_user)})")

    if not title:
        return ""
    if len(title) > 200:
        title = title[:197] + "..."
    return title.strip()



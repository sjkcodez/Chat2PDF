def run_session(session: Session):
    sid = session.id
    session_dir = config.SESSIONS_DIR / sid
    profile_dir = session_dir / "chrome_profile"
    output_pdf = session_dir / "output.pdf"
    snapshot_path = session_dir / "page_snapshot.html"

    prev_display = os.environ.get("DISPLAY")
    removed_proxies = _strip_proxies_from_env()
    using_real_display = _have_real_display()
    platform = _detect_platform(session.url)
    session.platform = platform

    print(f"[{sid}] Platform detected: {platform}")

    try:
        session_dir.mkdir(parents=True, exist_ok=True)
        template_exists = config.TEMPLATE_PROFILE.exists()

        if not using_real_display:
            display_num = _alloc_display()
            vnc_port = _alloc_port(config.VNC_PORT_START, config.VNC_PORT_END)
            ws_port = _alloc_port(config.WEBSOCKIFY_PORT_START,
                                  config.WEBSOCKIFY_PORT_END)
            display = f":{display_num}"
            session.touch("starting", f"Allocated display {display}")
            xvfb = _spawn(
                [config.XVFB_BIN, display, "-screen", "0", "1280x900x24",
                 "-nolisten", "tcp"], "xvfb", sid)
            session.procs.append(xvfb)
            time.sleep(0.8)
            x11vnc = _spawn(
                [config.X11VNC_BIN, "-display", display,
                 "-rfbport", str(vnc_port), "-localhost", "-nopw",
                 "-forever", "-shared", "-quiet"], "x11vnc", sid)
            session.procs.append(x11vnc)
            if not _wait_for_port(vnc_port, timeout=6):
                raise RuntimeError("x11vnc failed to start")
            session.touch("starting", "VNC ready")
            ws = _spawn(
                [config.WEBSOCKIFY_BIN, "--web", config.NOVNC_WEB_ROOT,
                 str(ws_port), f"127.0.0.1:{vnc_port}"], "websockify", sid)
            session.procs.append(ws)
            if not _wait_for_port(ws_port, timeout=6):
                raise RuntimeError("websockify failed to start")
            session.touch("starting", "noVNC ready")
            session.vnc_url = (
                f"http://localhost:{ws_port}/vnc.html"
                f"?autoconnect=1&resize=scale&reconnect=1"
            )
            os.environ["DISPLAY"] = display
            chrome_args = config.CHROME_ARGS_XVFB
        else:
            print(f"[{sid}] 🖥️  Using REAL display: {prev_display}")
            chrome_args = config.CHROME_ARGS_REAL_DISPLAY

        session.touch("loading", "Opening shared link…")
        if removed_proxies:
            print(f"[{sid}] Stripped proxy env vars: "
                  f"{list(removed_proxies.keys())}")

        max_attempts = 3
        for attempt_idx in range(max_attempts):
            if profile_dir.exists():
                shutil.rmtree(profile_dir, ignore_errors=True)
            if template_exists and config.TEMPLATE_PROFILE.exists():
                shutil.copytree(config.TEMPLATE_PROFILE, profile_dir)
                print(f"[{sid}] Copied warm profile")
            else:
                profile_dir.mkdir(parents=True, exist_ok=True)
                print(f"[{sid}] ⚠️  No trusted_template — fresh profile.")

            try:
                with sync_playwright() as p:
                    _attempt_conversion(
                        p, session, sid, session_dir, profile_dir,
                        output_pdf, snapshot_path, platform,
                        using_real_display, chrome_args)

                if not output_pdf.exists():
                    raise RuntimeError("PDF file was not created.")
                final_bytes = output_pdf.stat().st_size
                if final_bytes < 1000:
                    raise RuntimeError(
                        f"PDF too small ({final_bytes} bytes).")
                session.pdf_path = str(output_pdf)
                session.touch("done",
                              f"PDF ready ({final_bytes // 1024} KB).")
                print(f"[{sid}] Session marked done.")
                _maybe_save_template(sid, profile_dir)
                return

            except _RetryableNavigationError:
                if attempt_idx < max_attempts - 1:
                    print(f"[{sid}] 🔄 Recreating browser context "
                          f"(retry {attempt_idx + 2}/{max_attempts})…")
                    time.sleep(3)
                    continue
                else:
                    raise RuntimeError(
                        "Navigation failed with ERR_INVALID_ARGUMENT "
                        f"after {max_attempts} attempts.")
            except Exception as e:
                session.touch("failed", str(e))
                session.error = str(e)
                print(f"[{sid}] Session failed: {e}")
                return

    except Exception as e:
        session.touch("failed", str(e))
        session.error = str(e)
        print(f"[{sid}] Session failed: {e}")
    finally:
        _kill_procs(session.procs)
        if not using_real_display:
            if prev_display is None:
                os.environ.pop("DISPLAY", None)
            else:
                os.environ["DISPLAY"] = prev_display


def start_session(url: str, filename: str = None) -> Session:
    sid = uuid.uuid4().hex
    s = Session(id=sid, url=url, filename=filename)
    manager.add(s)
    t = threading.Thread(target=run_session, args=(s,), daemon=True)
    t.start()
    return s


def cleanup_session(sid: str):
    s = manager.get(sid)
    if not s:
        return
    s.cancel_requested = True
    _kill_procs(s.procs)
    manager.remove(sid)

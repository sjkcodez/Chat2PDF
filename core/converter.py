def _extract_conversation_html(page, context, snapshot_html, sid, url):
    result = None
    if page is not None and not page.is_closed():
        try:
            result = page.evaluate(_EXTRACT_JS)
        except Exception as e:
            print(f"[{sid}] Direct extraction failed: {e}")
    if not result or not result.get("html") or len(result["html"]) < 500:
        if page is not None and not page.is_closed():
            try:
                page.evaluate(_GENTLE_SCROLL_JS)
                _safe_wait(page, 2000)
                result = page.evaluate(_EXTRACT_JS)
            except Exception as e:
                print(f"[{sid}] Post-scroll extraction failed: {e}")
    if (not result or not result.get("html")
            or len(result["html"]) < 500) and snapshot_html:
        try:
            temp = context.new_page()
            try:
                temp.set_content(snapshot_html, wait_until="domcontentloaded")
                _safe_wait(temp, 800)
                result = temp.evaluate(_EXTRACT_JS)
            finally:
                try:
                    temp.close()
                except Exception:
                    pass
        except Exception as e:
            print(f"[{sid}] Snapshot extraction failed: {e}")
    if not result:
        return None, "", 0
    final_count = result.get("count", 0)
    print(f"[{sid}] Extracted {final_count} messages via DOM")
    return (result.get("html"),
            (result.get("first_text") or ""),
            final_count)



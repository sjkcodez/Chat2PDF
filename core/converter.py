def _chatgpt_dom_to_html(messages, sid: str):
    if not messages:
        return None, "", 0
    parts = []
    first_user = ""
    first_any = ""
    for m in messages:
        role = m.get("role", "assistant")
        text = m.get("text", "")
        candidate = text.strip().split("\n")[0][:100]
        if candidate:
            if not first_any and not _is_meta_message(candidate):
                first_any = candidate
            if (not first_user and role == "user"
                    and not _looks_like_code(candidate)
                    and not _is_meta_message(candidate)):
                first_user = candidate
        cleaned = _clean_chatgpt_markup(text)
        paragraphs = "".join(
            f"<p>{p}</p>" for p in cleaned.split("\n\n") if p.strip()
        ) or f"<p>{cleaned}</p>"
        parts.append(
            f'<section class="msg msg-{role}">{paragraphs}</section>'
        )
    if not first_user:
        first_user = first_any
    return "\n".join(parts), first_user, len(messages)



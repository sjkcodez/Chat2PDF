def _attempt_conversion(p, session, sid, session_dir, profile_dir,
                        output_pdf, snapshot_path, platform,
                        using_real_display, chrome_args):
    context = None
    try:
        context = _launch_context(p, profile_dir, chrome_args)
        context.add_init_script(
            "Object.defineProperty(navigator,'webdriver',"
            "{get:()=>undefined});"
            "window.chrome = window.chrome || { runtime: {} };"
        )
        page = context.new_page()
        try:
            page.on("crash", lambda: print(f"[{sid}] 🛑 PAGE CRASHED"))
        except Exception: pass
        try:
            page.on("close", lambda: print(f"[{sid}] 📕 PAGE CLOSED"))
        except Exception: pass
        try:
            if HAS_STEALTH_SYNC:
                stealth_sync_func(page)
            elif HAS_STEALTH_CLASS:
                StealthClass().apply_stealth_sync(page)
        except Exception as e:
            print(f"[{sid}] Stealth warning: {e}")

        conv_html = None
        fallback_first_user = ""

        if platform == "claude":
            print(f"[{sid}] Navigating to {session.url}")
            nav_ok = _navigate_claude_with_retry(page, context,
                                                 session.url, sid)
            if not nav_ok:
                raise RuntimeError("Could not navigate to Claude share page.")
            print(f"[{sid}] Waiting for Cloudflare to settle…")
            _safe_wait(page, 8000)
            if _claude_has_login_wall(page):
                raise RuntimeError(
                    "This Claude conversation requires sign-in. "
                    "Ask the owner to enable 'Public link'."
                )
            ready = _wait_for_claude(page, sid, timeout=120)
            if ready:
                snapshot_html = _safe_content(page)
                if snapshot_html:
                    try:
                        snapshot_path.write_text(snapshot_html, encoding="utf-8")
                        print(f"[{sid}] Saved snapshot: "
                              f"{len(snapshot_html)} chars")
                    except Exception as e:
                        print(f"[{sid}] Snapshot save failed: {e}")
                conv_html, fallback_first_user, _ = _extract_conversation_html(
                    page, context, snapshot_html, sid, session.url)

        else:
            print(f"[{sid}] Navigating to {session.url}")

            if platform == "gemini":
                nav_ok = False
                for attempt in (1, 2):
                    try:
                        if page.is_closed():
                            page = context.new_page()
                            try:
                                if HAS_STEALTH_SYNC:
                                    stealth_sync_func(page)
                                elif HAS_STEALTH_CLASS:
                                    StealthClass().apply_stealth_sync(page)
                            except Exception:
                                pass
                        page.goto(session.url,
                                  wait_until="domcontentloaded",
                                  timeout=45_000)
                        nav_ok = True
                        break
                    except Exception as e:
                        print(f"[{sid}] Gemini goto attempt "
                              f"{attempt} failed: {e}")
                        if attempt == 1:
                            _safe_wait(page, 2000)
                if not nav_ok:
                    raise _RetryableNavigationError("Gemini nav failed")
                _safe_wait(page, 2000)
                _accept_google_consent(page, sid)
                try:
                    current = page.url or ""
                    if "consent.google.com" in current:
                        print(f"[{sid}] Re-navigating after consent…")
                        page.goto(session.url,
                                  wait_until="domcontentloaded",
                                  timeout=45_000)
                        _safe_wait(page, 3000)
                except Exception as e:
                    print(f"[{sid}] Re-navigation failed: {e}")
                print(f"[{sid}] Waiting for Gemini app to boot…")
                _safe_wait(page, 5000)
            elif platform == "google_ai_mode":
                nav_ok = False
                for attempt in (1, 2):
                    try:
                        if page.is_closed():
                            page = context.new_page()
                        page.goto(session.url,
                                  wait_until="domcontentloaded",
                                  timeout=45_000)
                        nav_ok = True
                        break
                    except Exception as e:
                        print(f"[{sid}] Google AI Mode goto attempt "
                              f"{attempt} failed: {e}")
                        if attempt == 1:
                            _safe_wait(page, 2000)
                if not nav_ok:
                    raise _RetryableNavigationError("Google AI Mode nav failed")
                _safe_wait(page, 2000)
                _accept_google_consent(page, sid)
                try:
                    current = page.url or ""
                    if "consent.google.com" in current:
                        page.goto(session.url,
                                  wait_until="domcontentloaded",
                                  timeout=45_000)
                        _safe_wait(page, 3000)
                except Exception:
                    pass
                _safe_wait(page, 4000)
            else:
                nav_ok = False
                for attempt in (1, 2):
                    try:
                        if page.is_closed():
                            page = context.new_page()
                            try:
                                if HAS_STEALTH_SYNC:
                                    stealth_sync_func(page)
                                elif HAS_STEALTH_CLASS:
                                    StealthClass().apply_stealth_sync(page)
                            except Exception:
                                pass
                        page.goto(session.url,
                                  wait_until="domcontentloaded",
                                  timeout=45_000)
                        nav_ok = True
                        break
                    except Exception as e:
                        print(f"[{sid}] goto attempt {attempt} failed: {e}")
                        if "ERR_INVALID_ARGUMENT" in str(e):
                            raise _RetryableNavigationError(str(e))
                        if attempt == 1:
                            _safe_wait(page, 2000)
                if not nav_ok:
                    raise RuntimeError("Navigation failed after retry")

            if _page_has_captcha(page):
                if using_real_display:
                    session.touch("awaiting_captcha",
                                  "CAPTCHA is open in the Chrome window.")
                else:
                    session.touch("awaiting_captcha",
                                  "Human verification required.")
                deadline = time.time() + config.CAPTCHA_WAIT_SECONDS
                while time.time() < deadline:
                    if session.cancel_requested:
                        raise RuntimeError("Cancelled by user")
                    if _page_has(page, HARD_BLOCK_MARKERS):
                        raise RuntimeError("CloudFront hard block")
                    if not _page_has_captcha(page):
                        session.touch("rendering", "CAPTCHA solved.")
                        _safe_wait(page, 3000)
                        break
                    if not _safe_wait(page, 2000):
                        raise RuntimeError("Page died.")
                else:
                    raise RuntimeError("CAPTCHA wait timed out")

            if _page_has(page, HARD_BLOCK_MARKERS):
                raise RuntimeError("CloudFront hard block")

            session.touch("rendering", "Extracting conversation…")

            if platform == "chatgpt":
                print(f"[{sid}] Waiting for URL to stabilise…")
                _wait_for_url_stable(page, sid, max_wait_s=8.0)
                _safe_wait(page, 2000)

                _wait_for_platform_conversation(
                    page, platform, sid, timeout=60)

                api_html, api_first_user = _chatgpt_extract_via_api(
                    page, session.url, sid, max_retries=5)
                api_count = _count_messages(api_html)

                dom_messages = _chatgpt_collect_dom_messages(page, sid)
                dom_html, dom_first, dom_count = _chatgpt_dom_to_html(
                    dom_messages, sid)

                snapshot_html = _safe_content(page)
                if snapshot_html:
                    try:
                        snapshot_path.write_text(snapshot_html,
                                                 encoding="utf-8")
                        print(f"[{sid}] Saved snapshot: "
                              f"{len(snapshot_html)} chars")
                    except Exception as e:
                        print(f"[{sid}] Snapshot save failed: {e}")

                generic_html, generic_first, generic_count = \
                    _extract_conversation_html(page, context,
                                               snapshot_html, sid,
                                               session.url)

                candidates = [
                    ("API", api_html, api_first_user, api_count),
                    ("DOM-collect", dom_html, dom_first, dom_count),
                    ("DOM-generic", generic_html, generic_first,
                     generic_count),
                ]
                candidates.sort(key=lambda c: c[3], reverse=True)

                print(f"[{sid}] ChatGPT source comparison:")
                for name, _h, _f, n in candidates:
                    print(f"[{sid}]   {name:<12} → {n} messages")

                best_name, best_html, best_first, best_count = candidates[0]
                if best_count == 0 or not best_html:
                    raise RuntimeError(
                        "ChatGPT: no messages extracted from any source.")

                print(f"[{sid}] ➡️  Using {best_name} ({best_count} messages)")
                conv_html = best_html
                fallback_first_user = best_first

            else:
                ready, reason = _wait_for_platform_conversation(
                    page, platform, sid, timeout=120)
                print(f"[{sid}] Conversation ready: {ready} "
                      f"(reason={reason})")
                if not ready:
                    raise RuntimeError(
                        f"Timed out waiting for {platform}.")
                _safe_wait(page, 3000)
                snapshot_html = _safe_content(page)
                if snapshot_html:
                    try:
                        snapshot_path.write_text(snapshot_html,
                                                 encoding="utf-8")
                        print(f"[{sid}] Saved snapshot: "
                              f"{len(snapshot_html)} chars")
                    except Exception as e:
                        print(f"[{sid}] Snapshot save failed: {e}")
                conv_html, fallback_first_user, _ = _extract_conversation_html(
                    page, context, snapshot_html, sid, session.url)

        try:
            chat_title = _extract_chat_title(
                page, sid, fallback_text=fallback_first_user)
            if chat_title:
                session.chat_title = chat_title
                print(f"[{sid}] 📌 Chat title: {chat_title!r}")
            else:
                print(f"[{sid}] No chat title found — using default.")
        except Exception as e:
            print(f"[{sid}] Title extraction error: {e}")

        session.touch("rendering", "Rendering PDF…")
        final_size = 0

        # ---------------------------------------------------------------
        # Skip Layer 1 (direct page.pdf()) whenever we have BOTH extracted
        # content AND a chat title. Layer 1 uses the browser's own page
        # rendering, which does NOT include our custom header/title.
        # Layer 2 uses our template and is the only path that shows the
        # title we extracted.
        # ---------------------------------------------------------------
        has_extracted = bool(conv_html and len(conv_html) > 200)
        has_title = bool(session.chat_title)

        if has_extracted and has_title:
            skip_direct_pdf = True
            print(f"[{sid}] Skipping Layer 1 (title requires Layer 2)")
        else:
            skip_direct_pdf = platform in (
                "claude", "gemini", "chatgpt", "google_ai_mode",
                "perplexity", "grok", "meta", "copilot", "qwen",
            )

        if not skip_direct_pdf and not page.is_closed():
            try:
                page.pdf(path=str(output_pdf), format="A4",
                         print_background=True,
                         margin={"top": "15mm", "bottom": "15mm",
                                 "left": "12mm", "right": "12mm"})
                final_size = (output_pdf.stat().st_size
                              if output_pdf.exists() else 0)
                print(f"[{sid}] Layer 1 — direct page.pdf(): "
                      f"{final_size} bytes")
            except Exception as e:
                print(f"[{sid}] Layer 1 — direct page.pdf() failed: {e}")

        if final_size < 30_000 and conv_html and len(conv_html) > 200:
            print(f"[{sid}] Layer 2 — extracted {len(conv_html)} chars; "
                  f"re-rendering…")
            size = _render_extracted_pdf(
                context, conv_html, session.url, output_pdf, sid, session_dir,
                chat_title=session.chat_title)
            print(f"[{sid}] Layer 2 — extracted render: {size} bytes")
            if size > final_size:
                final_size = size

        if final_size < 20_000 and not page.is_closed():
            print(f"[{sid}] Layer 3 — screenshot fallback…")
            size = _screenshot_fallback(page, output_pdf, sid)
            print(f"[{sid}] Layer 3 — screenshot: {size} bytes")
            if size > final_size:
                final_size = size

        return final_size

    finally:
        if context is not None:
            try:
                context.close()
            except Exception:
                pass



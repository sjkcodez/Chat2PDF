def _have_real_display() -> bool:
    if os.environ.get("CHATPDF_FORCE_XVFB") == "1":
        return False
    disp = os.environ.get("DISPLAY")
    if not disp:
        return False
    m = re.match(r":(\d+)(?:\.\d+)?", disp)
    if not m:
        return False
    return Path(f"/tmp/.X11-unix/X{m.group(1)}").exists()


def _port_free(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind(("127.0.0.1", port))
            return True
        except OSError:
            return False


def _display_free(n: int) -> bool:
    return not Path(f"/tmp/.X{n}-lock").exists()


def _alloc_display() -> int:
    for n in range(config.XVFB_DISPLAY_START, config.XVFB_DISPLAY_END + 1):
        if _display_free(n):
            return n
    raise RuntimeError("No free X display slots")


def _alloc_port(start: int, end: int) -> int:
    for p in range(start, end + 1):
        if _port_free(p):
            return p
    raise RuntimeError(f"No free ports in {start}-{end}")


